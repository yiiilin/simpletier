// frameStore keeps a bounded, byte-limited copy of the frames one AF_PACKET
// sniffer observed. It is deliberately small: the acceptance only needs to
// answer "did this plaintext marker ever appear on this interface".
type frameStore struct {
	mu        sync.Mutex
	frames    [][]byte
	bytes     int64
	packets   int64
	maxBytes  int64
	maxFrames int
	truncated bool
}

func newFrameStore(maxBytes int64, maxFrames int) *frameStore {
	return &frameStore{maxBytes: maxBytes, maxFrames: maxFrames}
}

func (s *frameStore) add(frame []byte) {
	if s == nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.packets++
	if s.truncated || s.bytes >= s.maxBytes || len(s.frames) >= s.maxFrames {
		s.truncated = true
		return
	}
	copied := make([]byte, len(frame))
	copy(copied, frame)
	s.frames = append(s.frames, copied)
	s.bytes += int64(len(copied))
}

func (s *frameStore) reset() {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.frames = nil
	s.bytes = 0
	s.packets = 0
	s.truncated = false
}

func (s *frameStore) summary() map[string]any {
	s.mu.Lock()
	defer s.mu.Unlock()
	return map[string]any{
		"packets":   s.packets,
		"captured":  len(s.frames),
		"bytes":     s.bytes,
		"truncated": s.truncated,
	}
}

// findMarker returns the first captured frame that contains the plaintext
// marker, or nil.
func (s *frameStore) findMarker(marker []byte) []byte {
	frames := s.findMarkerFrames(marker, 1)
	if len(frames) == 0 {
		return nil
	}
	return frames[0]
}

// findMarkerFrames returns up to limit captured frames that contain the
// plaintext marker. Every plaintext byte that crossed the device is therefore
// classified by its own IPv4 header instead of by one arbitrary sample.
func (s *frameStore) findMarkerFrames(marker []byte, limit int) [][]byte {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make([][]byte, 0, limit)
	for _, frame := range s.frames {
		if indexOf(frame, marker) < 0 {
			continue
		}
		out = append(out, frame)
		if len(out) >= limit {
			break
		}
	}
	return out
}

// markerReport classifies every captured frame that carried the plaintext
// marker: how many, from which source, with which protocol, TTL and IPv4 total
// length. It is the evidence that the original IPv4 headers crossed the overlay
// unchanged, that the pinned TTL survived, and that nothing exceeded the frozen
// device MTU.
func markerReport(store *frameStore, marker []byte, limit int, pinnedTTL int, originVIP string) map[string]any {
	type srcStats struct {
		Frames    int            `json:"frames"`
		Protocols map[string]int `json:"protocols"`
		TTLs      map[string]int `json:"ttls"`
	}
	frames := store.findMarkerFrames(marker, limit)
	packets := make([]map[string]any, 0, len(frames))
	protocols := map[string]int{}
	ttls := map[string]int{}
	icmpOriginTTLs := map[string]int{}
	icmpPeerTTLs := map[string]int{}
	bySrc := map[string]*srcStats{}
	dataTTLs := map[int]bool{}
	originDataTTLs := map[string]int{}
	peerDataTTLs := map[string]int{}
	dataTTLUniform := true
	maxTotal := 0
	allIPv4 := true
	allWithinMTU := true
	for _, frame := range frames {
		description := describePacket(frame)
		packets = append(packets, description)
		protocol, hasProtocol := description["protocol"].(int)
		if !hasProtocol {
			allIPv4 = false
			continue
		}
		protocols[fmt.Sprintf("%d", protocol)]++
		ttl, hasTTL := description["ttl"].(int)
		if !hasTTL {
			allIPv4 = false
			continue
		}
		ttls[fmt.Sprintf("%d", ttl)]++
		src, _ := description["src"].(string)
		stats, ok := bySrc[src]
		if !ok {
			stats = &srcStats{Protocols: map[string]int{}, TTLs: map[string]int{}}
			bySrc[src] = stats
		}
		stats.Frames++
		stats.Protocols[fmt.Sprintf("%d", protocol)]++
		stats.TTLs[fmt.Sprintf("%d", ttl)]++
		total, hasTotal := description["total_length"].(int)
		if !hasTotal {
			allIPv4 = false
			continue
		}
		if total > maxTotal {
			maxTotal = total
		}
		if total > 1380 {
			allWithinMTU = false
		}
		if protocol == unix.IPPROTO_ICMP {
			// An ICMP echo request keeps the origin's pinned TTL across the
			// overlay; the echo reply is generated by the responder kernel and
			// carries that kernel's own default TTL. Both are recorded, so the
			// answer can be told apart from a re-originated request.
			if src == originVIP {
				icmpOriginTTLs[fmt.Sprintf("%d", ttl)]++
			} else {
				icmpPeerTTLs[fmt.Sprintf("%d", ttl)]++
			}
			continue
		}
		dataTTLs[ttl] = true
		if ttl != pinnedTTL {
			dataTTLUniform = false
		}
		// Split by origin: the same-origin histogram is what makes TTL opacity
		// a cross-TUN comparison instead of a same-host assumption.
		if src == originVIP {
			originDataTTLs[fmt.Sprintf("%d", ttl)]++
		} else {
			peerDataTTLs[fmt.Sprintf("%d", ttl)]++
		}
	}
	values := make([]int, 0, len(dataTTLs))
	for value := range dataTTLs {
		values = append(values, value)
	}
	sort.Ints(values)
	report := map[string]any{
		"marker_found":     len(frames) > 0,
		"marker_frames":    len(frames),
		"packets":          packets,
		"protocols":        protocols,
		"ttls":             ttls,
		"by_src":           bySrc,
		"pinned_ttl":       pinnedTTL,
		"origin_vip":       originVIP,
		"data_ttl_uniform": dataTTLUniform,
		"data_ttl_values":  values,
		"origin_data_ttls": originDataTTLs,
		"peer_data_ttls":   peerDataTTLs,
		"icmp_origin_ttls": icmpOriginTTLs,
		"icmp_peer_ttls":   icmpPeerTTLs,
		"max_total_len":    maxTotal,
		"all_ipv4":         allIPv4,
		"within_mtu_1380":  allWithinMTU,
	}
	return report
}

func indexOf(haystack, needle []byte) int {
	if len(needle) == 0 || len(haystack) < len(needle) {
		return -1
	}
	first := needle[0]
	for i := 0; i+len(needle) <= len(haystack); i++ {
		if haystack[i] != first {
			continue
		}
		match := true
		for j := 1; j < len(needle); j++ {
			if haystack[i+j] != needle[j] {
				match = false
				break
			}
		}
		if match {
			return i
		}
	}
	return -1
}

// sniffer captures every frame the kernel delivers on one interface of this
// namespace.
type sniffer struct {
	name  string
	fd    int
	store *frameStore
	stop  chan struct{}
	done  chan struct{}
	err   atomic.Pointer[string]
}

func startSniffer(name string) (*sniffer, error) {
	iface, err := net.InterfaceByName(name)
	if err != nil {
		return nil, fmt.Errorf("sniffer: interface %q: %w", name, err)
	}
	protocol := int(htons(unix.ETH_P_ALL))
	fd, err := unix.Socket(unix.AF_PACKET, unix.SOCK_RAW|unix.SOCK_CLOEXEC, protocol)
	if err != nil {
		return nil, fmt.Errorf("sniffer: open AF_PACKET on %s: %w", name, err)
	}
	if err := unix.Bind(fd, &unix.SockaddrLinklayer{Protocol: uint16(protocol), Ifindex: iface.Index}); err != nil {
		unix.Close(fd)
		return nil, fmt.Errorf("sniffer: bind AF_PACKET to %s: %w", name, err)
	}
	timeout := unix.Timeval{Sec: 0, Usec: 200000}
	if err := unix.SetsockoptTimeval(fd, unix.SOL_SOCKET, unix.SO_RCVTIMEO, &timeout); err != nil {
		unix.Close(fd)
		return nil, fmt.Errorf("sniffer: set receive timeout on %s: %w", name, err)
	}
	s := &sniffer{
		name:  name,
		fd:    fd,
		store: newFrameStore(8<<20, 20000),
		stop:  make(chan struct{}),
		done:  make(chan struct{}),
	}
	go s.loop()
	return s, nil
}

func (s *sniffer) loop() {
	defer close(s.done)
	buf := make([]byte, 1<<16)
	for {
		select {
		case <-s.stop:
			return
		default:
		}
		n, _, err := unix.Recvfrom(s.fd, buf, 0)
		if err != nil {
			if err == unix.EAGAIN || err == unix.EWOULDBLOCK || err == unix.EINTR {
				continue
			}
			message := fmt.Sprintf("capture on %s stopped: %v", s.name, err)
			s.err.Store(&message)
			return
		}
		if n > 0 {
			s.store.add(buf[:n])
		}
	}
}

func (s *sniffer) Close() {
	if s == nil {
		return
	}
	close(s.stop)
	<-s.done
	unix.Close(s.fd)
}

func (s *sniffer) error() string {
	if message := s.err.Load(); message != nil {
		return *message
	}
	return ""
}

func htons(value uint16) uint16 { return value<<8 | value>>8 }

// ipv4 payload parsing of one captured frame: veth frames carry an Ethernet
// header, tun frames start directly with the IPv4 header.
func frameIPv4(frame []byte) ([]byte, bool) {
	if len(frame) >= 14 {
		if binary.BigEndian.Uint16(frame[12:14]) == 0x0800 {
			return frame[14:], true
		}
	}
	if len(frame) >= 20 && frame[0]>>4 == 4 {
		return frame, true
	}
	return nil, false
}

// describePacket reports the IPv4 header facts of the first captured frame
// that carries the marker. It is how the acceptance proves that TTL, total
// length and protocol crossed the overlay unchanged.
func describePacket(frame []byte) map[string]any {
	payload, ok := frameIPv4(frame)
	if !ok || len(payload) < 20 {
		return map[string]any{"ipv4": false}
	}
	ihl := int(payload[0]&0x0f) * 4
	if ihl < 20 || len(payload) < ihl {
		return map[string]any{"ipv4": false}
	}
	totalLength := int(binary.BigEndian.Uint16(payload[2:4]))
	protocol := payload[9]
	return map[string]any{
		"ipv4":         true,
		"ttl":          int(payload[8]),
		"protocol":     int(protocol),
		"total_length": totalLength,
		"src":          netip.AddrFrom4([4]byte{payload[12], payload[13], payload[14], payload[15]}).String(),
		"dst":          netip.AddrFrom4([4]byte{payload[16], payload[17], payload[18], payload[19]}).String(),
	}
}

// newMarker builds a unique, high-entropy 64-byte ASCII marker. A marker that
// is present in the plaintext but absent from the ciphertext is the evidence
// that the link really encrypts.
func newMarker() ([]byte, error) {
	random := make([]byte, 24)
	if _, err := rand.Read(random); err != nil {
		return nil, fmt.Errorf("generate payload marker: %w", err)
	}
	marker := []byte("TUN-ACCEPT-MARKER-" + hex.EncodeToString(random) + "-PAYLOAD")
	if len(marker) < 48 {
		return nil, fmt.Errorf("generated marker is unexpectedly short")
	}
	return marker, nil
}

func markerFromHex(hexText string) ([]byte, error) {
	raw, err := hex.DecodeString(hexText)
	if err != nil {
		return nil, fmt.Errorf("decode marker: %w", err)
	}
	if len(raw) < 32 {
		return nil, fmt.Errorf("marker must be at least 32 bytes, got %d", len(raw))
	}
	return raw, nil
}

// buildPayload fills one payload with the marker repeated to the requested
// size, so a substring search is decisive for any MTU-sized datagram.
func buildPayload(marker []byte, size int) []byte {
	payload := make([]byte, size)
	for offset := 0; offset < size; offset += len(marker) {
		copy(payload[offset:], marker)
	}
	return payload
}

// ttlControl returns a net.Dialer/ListenConfig control hook that pins the
// outgoing IPv4 TTL. A non-default TTL that survives to the peer's TUN proves
// the overlay carries the original IPv4 header opaquely instead of
// re-originating a connection.
func ttlControl(ttl int) func(network, address string, raw syscall.RawConn) error {
	return func(_, _ string, raw syscall.RawConn) error {
		var sockErr error
		if err := raw.Control(func(fd uintptr) {
			sockErr = unix.SetsockoptInt(int(fd), unix.IPPROTO_IP, unix.IP_TTL, ttl)
		}); err != nil {
			return err
		}
		return sockErr
	}
}

// icmpEcho sends one ICMP echo request through the kernel routing table (so it
// must leave through the TUN) and returns the reply facts.
type icmpResult struct {
	Replied     bool
	ReplySrc    string
	TTL         int
	PayloadHash string
	RTT         time.Duration
}

func icmpEcho(ctx context.Context, src, dst netip.Addr, payload []byte, id, seq uint16, ttl int, timeout time.Duration) (icmpResult, error) {
	fd, err := unix.Socket(unix.AF_INET, unix.SOCK_RAW|unix.SOCK_CLOEXEC, unix.IPPROTO_ICMP)
	if err != nil {
		return icmpResult{}, fmt.Errorf("open raw ICMP socket: %w", err)
	}
	defer unix.Close(fd)
	if err := unix.Bind(fd, &unix.SockaddrInet4{Addr: src.As4()}); err != nil {
		return icmpResult{}, fmt.Errorf("bind raw ICMP socket to %s: %w", src, err)
	}
	if err := unix.SetsockoptInt(fd, unix.IPPROTO_IP, unix.IP_TTL, ttl); err != nil {
		return icmpResult{}, fmt.Errorf("pin ICMP TTL to %d: %w", ttl, err)
	}
	deadline := unix.Timeval{Sec: int64(timeout / time.Second), Usec: int64((timeout % time.Second) / time.Microsecond)}
	if err := unix.SetsockoptTimeval(fd, unix.SOL_SOCKET, unix.SO_RCVTIMEO, &deadline); err != nil {
		return icmpResult{}, fmt.Errorf("set ICMP receive timeout: %w", err)
	}

	request := make([]byte, 8+len(payload))
	request[0] = 8 // echo request
	request[1] = 0
	binary.BigEndian.PutUint16(request[4:], id)
	binary.BigEndian.PutUint16(request[6:], seq)
	copy(request[8:], payload)
	binary.BigEndian.PutUint16(request[2:], icmpChecksum(request))

	started := time.Now()
	if err := unix.Sendto(fd, request, 0, &unix.SockaddrInet4{Addr: dst.As4()}); err != nil {
		return icmpResult{}, fmt.Errorf("send ICMP echo to %s: %w", dst, err)
	}

	buf := make([]byte, 4096)
	for {
		select {
		case <-ctx.Done():
			return icmpResult{}, fmt.Errorf("%w while waiting for an ICMP echo reply from %s", ctx.Err(), dst)
		default:
		}
		n, from, err := unix.Recvfrom(fd, buf, 0)
		if err != nil {
			if err == unix.EAGAIN || err == unix.EWOULDBLOCK {
				if time.Since(started) > timeout {
					return icmpResult{Replied: false}, nil
				}
				continue
			}
			return icmpResult{}, fmt.Errorf("receive ICMP reply: %w", err)
		}
		if n < 28 {
			continue
		}
		ihl := int(buf[0]&0x0f) * 4
		if ihl < 20 || n < ihl+8 {
			continue
		}
		if buf[9] != unix.IPPROTO_ICMP {
			continue
		}
		icmp := buf[ihl:n]
		if icmp[0] != 0 || icmp[1] != 0 { // echo reply
			continue
		}
		if binary.BigEndian.Uint16(icmp[4:]) != id || binary.BigEndian.Uint16(icmp[6:]) != seq {
			continue
		}
		fromAddr, _ := from.(*unix.SockaddrInet4)
		replySrc := dst
		if fromAddr != nil {
			replySrc = netip.AddrFrom4(fromAddr.Addr)
		}
		return icmpResult{
			Replied:     true,
			ReplySrc:    replySrc.String(),
			TTL:         int(buf[8]),
			PayloadHash: hashHex(icmp[8:]),
			RTT:         time.Since(started),
		}, nil
	}
}

func icmpChecksum(data []byte) uint16 {
	var sum uint32
	for index := 0; index+1 < len(data); index += 2 {
		sum += uint32(data[index])<<8 | uint32(data[index+1])
	}
	if len(data)%2 == 1 {
		sum += uint32(data[len(data)-1]) << 8
	}
	for sum>>16 != 0 {
		sum = (sum & 0xffff) + (sum >> 16)
	}
	return ^uint16(sum)
}
