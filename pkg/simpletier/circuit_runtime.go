// circuitAdapter is the bridge between the component-level Circuit manager and
// the Network data plane.
//
// CryptoProvider seam: internal/circuit's ProtectPayload(ref, dir, plaintext)
// carries no MessageKind, and the E2E AEAD commits the envelope MessageType into
// its AAD, so this adapter deliberately does NOT claim to be the crypto. It
// returns the owned logical bytes unchanged; the real inner AEAD is applied by
// Egress below, which does receive Submission.Kind. Nothing here infers a
// message kind from an opaque CircuitID.
type circuitAdapter struct {
	rt *streamRuntime
}

func (a *circuitAdapter) ProtectPayload(ref circuit.SessionRef, dir circuit.Direction, plaintext []byte) ([]byte, error) {
	if a == nil || a.rt == nil {
		return nil, circuit.ErrCryptoUnavailable
	}
	entry := a.rt.sessionEntryByID(session.SessionID(ref.ID))
	if entry == nil {
		return nil, fmt.Errorf("%w: unknown session", circuit.ErrInvalidSession)
	}
	if !entry.isReady() || entry.isTerminated() {
		return nil, fmt.Errorf("%w: session is not committed", circuit.ErrSessionLost)
	}
	// Return the caller's bytes instead of a copy. This adapter is explicitly not
	// the crypto (see the type comment above): the only consumer is Egress, which
	// passes the body to the session protector's Seal as read-only plaintext and
	// never writes through it. Copying here cost one full payload allocation per
	// frame on the hottest path for no isolation benefit.
	return plaintext, nil
}

// AdmitOpen is the synchronous all-or-none CIRCUIT_OPEN admission. It resolves
// the session, data link, hop route and nonce before any byte is written, seals
// the complete frame and only then queues it, so a returned Committed means the
// whole frame is queued in order and a definitive refusal never wrote anything.
func (a *circuitAdapter) AdmitOpen(ctx context.Context, sub circuit.Submission) (circuit.Admission, error) {
	if a == nil || a.rt == nil {
		return 0, circuit.ErrEgressUnavailable
	}
	err := a.rt.sendCircuitFrame(sub)
	if err != nil {
		if errors.Is(err, errNoDataPath) || errors.Is(err, ErrResource) {
			return circuit.AdmissionRefused, nil
		}
		return 0, err
	}
	return circuit.AdmissionCommitted, nil
}

func (a *circuitAdapter) Send(ctx context.Context, sub circuit.Submission) error {
	if a == nil || a.rt == nil {
		return circuit.ErrEgressUnavailable
	}
	if err := a.rt.sendCircuitFrame(sub); err != nil {
		traceSealLost("adapter-send", a.rt.sessionEntryByID(session.SessionID(sub.Session.ID)), err)
		return fmt.Errorf("%w: %w", circuit.ErrSessionLost, err)
	}
	return nil
}

var errNoDataPath = errors.New("no ready stream data path")

// chargeEgressControlRPC spends one shared per-Link/Network control token for
// one outbound Circuit submission immediately before it is sealed or enqueued,
// on the exact pinned physical Link. The frozen wire classification is by
// MessageType: every CONTROL_RPC opcode spends a token, WINDOW_UPDATE included,
// and only STREAM_DATA is exempt. A refusal is a Circuit-scoped resource error
// so the Manager resets only the offending Circuit.
func (rt *streamRuntime) chargeEgressControlRPC(pump *controlPump, sub circuit.Submission) error {
	if rt == nil || rt.n == nil || pump == nil || sub.Kind != circuit.KindControlRPC {
		return nil
	}
	// Receive-side credit feedback is exempt: it is generated by this node's own
	// drain rate, so a peer cannot amplify it, and charging it made the per-Link
	// control budget (sized for open/ready/reset) cap bulk throughput at one
	// window per token. The ingress half applies the same exemption so the two
	// directions agree on what costs a token.
	if sub.FlowControl {
		return nil
	}
	if err := rt.n.awaitEgressControl(rt.n.ctx, pump.linkKey.LinkID, pump.linkKey.Epoch); err != nil {
		traceDataPlane("CONTROL_RPC egress control budget exhausted", "err", err.Error())
		return fmt.Errorf("%w: %v", circuit.ErrResource, err)
	}
	return nil
}

// chargeRelayControlRPC spends one shared per-Link/Network control token for one
// opaque relay frame whose authenticated envelope names CONTROL_RPC. A relay
// never decrypts the inner payload, so the budget class comes from the envelope
// MessageType alone. ingress selects the arrival half on the exact ingress Link;
// otherwise it is the forward half on the exact outbound Link. Each half is
// charged exactly once per traversal: ingress on the initial arrival (before
// staging or forwarding), egress when the frame is actually forwarded, so a
// staged frame is never re-counted when its drain forwards it. A refusal is a
// scoped drop of this one control frame; the physical Link and every other
// Session stay healthy.
func (rt *streamRuntime) chargeRelayControlRPC(pump *controlPump, ingress bool) error {
	if rt == nil || rt.n == nil || pump == nil {
		return nil
	}
	await := rt.n.awaitEgressControl
	if ingress {
		await = rt.n.awaitIngressControl
	}
	if err := await(rt.n.ctx, pump.linkKey.LinkID, pump.linkKey.Epoch); err != nil {
		traceDataPlane("relay CONTROL_RPC control budget exhausted", "ingress", ingress, "err", err.Error())
		return err
	}
	return nil
}

// sealCircuitFrame builds and queues the E2E frame of one Circuit submission
// under the single session egress lock: the MessageNumber allocation, the inner
// AEAD seal and the enqueue into the Link's unique writer queue are ONE critical
// section. If only the seal were serialized, two producers of the same session
// direction could interleave as A(number 0) seal, B(number 1) seal+enqueue,
// A(number 0) enqueue; the writer would then observe 1 before 0 and the link
// layer's strict nonce advance would fail closed with ErrNonceReuse, tearing
// down the shared Link. Holding the lock through enqueue makes physical wire
// order identical to allocation order. The enqueue never blocks (a full queue is
// ErrResource), so the lock is only held across bounded local work.
func (rt *streamRuntime) sendCircuitFrame(sub circuit.Submission) error {
	entry := rt.sessionEntryByID(session.SessionID(sub.Session.ID))
	if entry == nil {
		return fmt.Errorf("%w: unknown session", circuit.ErrInvalidSession)
	}
	if !entry.isReady() || entry.isTerminated() {
		return fmt.Errorf("%w: session is not committed", circuit.ErrSessionLost)
	}
	ps := rt.pathByScope(entry.scope)
	if ps == nil {
		return errNoDataPath
	}
	entry.protMu.Lock()
	tx := entry.tx
	entry.protMu.Unlock()
	if tx == nil {
		traceSealLost("protectors-nil", entry, fmt.Errorf("session protectors are not installed"))
		return fmt.Errorf("%w: session protectors are not installed", circuit.ErrSessionLost)
	}

	// The direction tells us which endpoint is the actual sender: the E2E
	// envelope carries the real sender/receiver, while the Session's own
	// canonical endpoints stay the selected handshake pair. DirectionSourceToTarget
	// always means "the canonical source is sending", independent of which side
	// this node is.
	senderIsSource := sub.Direction == circuit.DirectionSourceToTarget
	var src, dst [16]byte
	if senderIsSource {
		src, dst = entry.src, entry.dst
	} else {
		src, dst = entry.dst, entry.src
	}
	// The STREAM hop is the adjacent hop toward the final destination.
	dstIndex := 0
	for index, node := range ps.nodes {
		if [16]byte(node) == dst {
			dstIndex = index
			break
		}
	}
	outIndex := ps.hopIndexToward(dstIndex)
	if outIndex < 0 || outIndex >= len(ps.nodes) {
		return errNoDataPath
	}
	pump := rt.dataPumpOnPath(ps, outIndex)
	if pump == nil {
		// Losing the pinned hop is a lost Session for this Circuit: never migrate
		// to a sibling Link or to another data lane.
		traceSealLost("pinned-stream-hop", entry, fmt.Errorf("pinned STREAM hop is not the installed Link instance"))
		return fmt.Errorf("%w: pinned STREAM hop is not the installed Link instance", circuit.ErrSessionLost)
	}
	class, err := classOfLane(ps.lane)
	if err != nil {
		return err
	}
	if err := rt.chargeEgressControlRPC(pump, sub); err != nil {
		return err
	}
	if err := pump.control.AdmitSession([16]byte(entry.id), byte(class)); err != nil {
		return err
	}
	if err := rt.awaitSealHeadroom(entry, tx); err != nil {
		traceSealLost("await-headroom", entry, err)
		return err
	}
	entry.txMu.Lock()
	defer entry.txMu.Unlock()
	// The KeyEpoch is read from the installed TX protector under txMu, the same
	// lock the install path takes, so an epoch install can never race this seal.
	// A frame already queued keeps the epoch it was built with; this only stamps
	// the committed installed epoch, never a hardcoded 1.
	epoch, number, err := rt.nextSealIdentity(entry, tx)
	if err != nil {
		return err
	}
	envelope := buildEnvelope(rt.wireID, src, dst, wire.MessageType(sub.Kind), [16]byte(entry.id), epoch, number, entry.scope.id, entry.scope.gen, len(sub.Body))
	frame := wire.Frame{Kind: wire.FrameKindEndToEnd, Envelope: envelope}
	sealed, err := tx.Seal(frame, sub.Body)
	if err != nil {
		return traceSealLost("tx-seal", entry, err)
	}
	traceDataPlane("E2E sealed", "kind", uint8(sub.Kind), "number", number, "plain_len", len(sub.Body), "session", hexNode([16]byte(entry.id))[:8])
	if err := pump.sendEndToEnd(sealed.Envelope, sealed.Body, link.HopRoute{Cursor: uint8(outIndex), HopLimit: overlayHopLimit, RemainingBudget: ps.pathBudget()}); err != nil {
		return traceSealLost("enqueue", entry, err)
	}
	return nil
}

// --- inbound E2E dispatch ----------------------------------------------------

// handleEndToEndFrame handles one hop-authenticated E2E frame read from a STREAM
// link. Exactly the endpoint pair that owns the Session root opens the inner
// AEAD and commits the hop replay floor; an intermediate relay validates only
// what it can authenticate (installed path, admitted session, hop domain) and
// forwards the opaque ciphertext without ever holding the E2E root.
func (rt *streamRuntime) handleEndToEndFrame(pump *controlPump, message link.ProtectedMessage) error {
	if len(message.Envelope) != wire.EnvelopeSize {
		return link.ErrEndToEndMessage
	}
	// The frozen envelope locator must name exactly this Network. Zero is a
	// legal equality, not a wildcard: the full-context hop KDF is the real
	// isolation root, but a foreign-network frame is rejected before any state
	// is touched.
	if envelopeWireID(message.Envelope) != rt.wireID {
		return link.ErrEndToEndMessage
	}
	dst := envelopeNode(message.Envelope, envelopeDstOffset)
	if pump.lane != laneStream && pump.lane != lanePacket {
		return link.ErrUnexpectedKind
	}
	pathID, pathGen := envelopePath(message.Envelope)
	if dst == rt.localID {
		if err := rt.openLocalEndToEnd(pump, message, pathID, pathGen); err != nil {
			traceDataPlane("E2E local delivery failed", "kind", uint8(envelopeMessageType(message.Envelope)), "err", err.Error())
			return err
		}
		return nil
	}
	if err := rt.forwardEndToEnd(pump, message, pathID, pathGen); err != nil {
		traceDataPlane("E2E relay failed", "kind", uint8(envelopeMessageType(message.Envelope)), "err", err.Error())
		return err
	}
	return nil
}

// openLocalEndToEnd handles an E2E frame whose final destination is this node.
// A Session that has not committed its READY must not expose its root: the frame
// is staged as hop-authenticated inner ciphertext under the frozen per-Session
// pending budget and only decrypted (with its hop floor committed) after READY.
func (rt *streamRuntime) openLocalEndToEnd(pump *controlPump, message link.ProtectedMessage, pathID uint64, pathGen uint32) error {
	sessionID := envelopeSessionID(message.Envelope)
	entry := rt.sessionEntryByID(session.SessionID(sessionID))
	if entry == nil {
		return link.ErrSessionNotAdmitted
	}
	// Before the staged ciphertext or the Session root is touched: the envelope
	// Path scope must be the session's installed scope, the Path lane must map
	// to the session's class, the wire src/dst must be exactly the logical
	// endpoints of that direction, and the frame must have been read from the
	// physical adjacent hop the direction requires with the exact installed
	// STREAM LinkID/LinkEpoch/Lane.
	if entry.scope.id != pathID || entry.scope.gen != pathGen {
		return link.ErrEndToEndMessage
	}
	ps := rt.pathByScope(entry.scope)
	if ps == nil {
		return link.ErrEndToEndMessage
	}
	class, err := classOfLane(ps.lane)
	if err != nil || class != entry.class {
		return link.ErrEndToEndMessage
	}
	forward, reverse := ps.directionOnPath(message.Envelope)
	if !forward && !reverse {
		return link.ErrEndToEndMessage
	}
	if int(message.Hop().Cursor) != ps.localIndex {
		return link.ErrInvalidHopRoute
	}
	if err := rt.checkIngressPeer(ps, pump, forward, true); err != nil {
		return err
	}
	entry.pendMu.Lock()
	if !entry.pendReady {
		entry.pendMu.Unlock()
		rt.stageInboundFrame(entry, pump, message)
		return nil
	}
	entry.pendMu.Unlock()

	entry.protMu.Lock()
	rx := entry.rx
	rxEpoch := uint32(0)
	if rx != nil {
		rxEpoch = rx.CurrentEpoch()
	}
	entry.protMu.Unlock()
	if rx == nil {
		return link.ErrSessionNotAdmitted
	}
	epoch := envelopeEpoch(message.Envelope)
	if epoch == 0 || epoch > rxEpoch {
		// A future epoch may only be staged opaquely when a coalesced next
		// attempt is in flight and its target epoch is exactly this one. An
		// early future epoch with no registered attempt is dropped: it never
		// poisons the session, the Path or the shared tag ledger.
		if !entry.rekeyAcceptsEpoch(epoch) {
			return nil
		}
		rt.stageInboundFrame(entry, pump, message)
		return nil
	}
	frame := wire.Frame{Kind: wire.FrameKindEndToEnd, Envelope: message.Envelope, Body: message.Payload}
	plaintext, err := rx.Open(frame)
	if err != nil {
		// A failed tag, replay or binding mismatch never moves the hop floor and
		// never delivers plaintext. The failure is scoped to this Session/Path
		// and never reported as a global healthy-Link failure, but it is traced
		// so a drop is never invisible.
		traceDataPlane("E2E open dropped", "session", hexNode([16]byte(entry.id))[:8], "epoch", epoch,
			"rx_current", rxEpoch, "number", envelopeNumber(message.Envelope), "err", err.Error())
		return nil
	}
	// Only a frame authenticated under the RX protector's CURRENT epoch may
	// start the TX side's previous-epoch retirement clock. An old (grace) epoch
	// frame is delivered but never marks.
	rt.recordAuthenticatedEpoch(entry, message.Envelope, rxEpoch)
	number := envelopeNumber(message.Envelope)
	if err := pump.control.CommitEndToEnd(sessionID, epoch, number); err != nil {
		return nil
	}
	traceDataPlane("E2E opened", "kind", uint8(envelopeMessageType(message.Envelope)), "number", number, "plain_len", len(plaintext))
	return rt.deliverOpenedFrame(message, entry, plaintext, pump)
}

// stageInboundFrame holds one hop-authenticated inbound E2E frame, unopened,
// under the frozen per-Session pending count and byte ceiling. The shared
// allocator composite (exact copied envelope+body as Data under the physical
// ingress Link, plus the pendingFrame metadata as State) is booked before either
// copy; the per-Session ReservePending ceiling is the secondary bound. Every
// reservation is released exactly once by drain/drop/close. No inner layer is
// decoded or opened here.
//
// A shared-allocator refusal or a per-Session ceiling refusal drops only this
// frame: the Session and the physical Link stay up, and nothing is admitted
// unaccounted.
func (rt *streamRuntime) stageInboundFrame(entry *sessionEntry, pump *controlPump, message link.ProtectedMessage) {
	if entry == nil || entry.sess == nil {
		return
	}
	entry.pendMu.Lock()
	if entry.stagedClosed {
		entry.pendMu.Unlock()
		return
	}
	if len(entry.pending) >= pendingSessionFrames || entry.pendBytes+len(message.Payload) > session.MaxPendingBytes {
		entry.pendMu.Unlock()
		return
	}
	lease, err := rt.n.reservePendingCiphertext(pump, len(message.Envelope), len(message.Payload))
	if err != nil {
		entry.pendMu.Unlock()
		traceDataPlane("staged inbound frame refused; Session failed",
			"session", hexNode([16]byte(entry.id))[:8], "err", err.Error())
		rt.failStagedInboundRefusal(entry)
		return
	}
	if err := entry.sess.ReservePending(len(message.Payload)); err != nil {
		// All-or-none: the shared composite is returned before this frame owns
		// any copy, and the refusal fails only this Session.
		entry.pendMu.Unlock()
		_ = lease.Release()
		traceDataPlane("staged inbound frame over the per-Session ceiling; Session failed",
			"session", hexNode([16]byte(entry.id))[:8], "err", err.Error())
		rt.failStagedInboundRefusal(entry)
		return
	}
	entry.pending = append(entry.pending, pendingFrame{
		pump:                  pump,
		envelope:              append([]byte(nil), message.Envelope...),
		body:                  append([]byte(nil), message.Payload...),
		message:               envelopeMessageType(message.Envelope),
		hop:                   message.Hop(),
		reserved:              len(message.Payload),
		hasSessionReservation: true,
		lease:                 lease,
		protected:             message,
	})
	entry.pendBytes += len(message.Payload)
	entry.pendMu.Unlock()
}

// deliverOpenedFrame routes one authenticated inner plaintext to its endpoint
// core by MessageType. IP_PACKET reaches the L3 packet plane and UDP_DATAGRAM the
// Flow UDP plane; every other type is the Circuit STREAM plane. A missing core is
// dropped, never delivered and never a link failure.
func (rt *streamRuntime) deliverOpenedFrame(message link.ProtectedMessage, entry *sessionEntry, plaintext []byte, pump *controlPump) error {
	switch envelopeMessageType(message.Envelope) {
	case wire.MessageTypeIPPacket:
		return rt.deliverPacketFrame(message, plaintext)
	case wire.MessageTypeUDPDatagram:
		return rt.deliverDatagramFrame(message, plaintext)
	default:
		return rt.deliverCircuitFrame(envelopeMessageType(message.Envelope), message.Envelope, entry, plaintext, pump)
	}
}

// chargeIngressControlRPC spends one shared per-Link/Network control token for
// one already-authenticated inbound CONTROL_RPC before any of its state is
// touched. It returns true when the frame may proceed. On a refusal it is a
// scoped, non-silent outcome: it traces (and the limiter already counted the
// control wait timeout), aborts and latches terminal only the offending
// Session, and returns false so the caller stops without decoding. The physical
// Link is never torn down by one Session's control pressure.
func (rt *streamRuntime) chargeIngressControlRPC(pump *controlPump, entry *sessionEntry) bool {
	if rt == nil || rt.n == nil || pump == nil {
		return true
	}
	if err := rt.n.awaitIngressControl(rt.n.ctx, pump.linkKey.LinkID, pump.linkKey.Epoch); err != nil {
		if entry != nil {
			traceDataPlane("CONTROL_RPC ingress control budget exhausted; Session failed",
				"session", hexNode([16]byte(entry.id))[:8], "err", err.Error())
			if entry.sess != nil {
				_ = entry.sess.Abort()
			}
			// Make the failure observable to every circuit-facing boundary:
			// isReady() stays true and the protectors stay installed, so without
			// this latch outgoing Circuits would keep sending on a dead Session.
			entry.markTerminated()
			// Session.Abort notifies the circuit manager of nothing: a blocked
			// circuitStream.Read waits on its Circuit's own wake channel, which
			// only a Circuit-layer terminal transition signals. FailSession
			// terminalizes this Session's Circuits locally, wakes their readers
			// with ErrSessionLost, and refuses later Opens for the same scope;
			// it submits no wire frame and closes no Link.
			if err := rt.circuits.FailSession(circuit.SessionRef{
				ID:             circuit.SessionID(entry.id),
				PathID:         entry.scope.id,
				PathGeneration: entry.scope.gen,
			}, circuit.ErrSessionLost); err != nil {
				traceDataPlane("scoped Session Circuits not failed",
					"session", hexNode([16]byte(entry.id))[:8], "err", err.Error())
			}
		}
		return false
	}
	return true
}

// classOfLane is the pkg-private validated mapping from a Path Lane to the
// session class that carries it. There is deliberately no public session API for
// this: an unknown lane is a local wiring bug and fails closed.
func classOfLane(lane path.Lane) (session.SessionClass, error) {
	switch lane {
	case path.LanePacket:
		return session.SessionClassPacket, nil
	case path.LaneStream:
		return session.SessionClassStream, nil
	default:
		return 0, fmt.Errorf("%w: unknown data lane 0x%02x", ErrInvalidConfig, uint8(lane))
	}
}

// deliverCircuitFrame decodes one authenticated inner plaintext and hands it to
// the Circuit manager. It is the only place where business plaintext exists.
//
// Every decoded control/data message is envelope-owned: DecodeOpenMessage,
// DecodeReadyMessage, DecodeResetMessage, DecodeWindowUpdate and
// DecodeStreamData all leave FromNodeID zero and OpenMessage.Session empty. The
// circuit layer keys and correlates on those fields, so they MUST be filled from
// the authenticated envelope (src) and the arrival session before any state
// change. A zero FromNodeID silently resolves to no record, which is why the
// envelope is threaded here for every codec (including the pending drain).
func (rt *streamRuntime) deliverCircuitFrame(messageType wire.MessageType, envelope []byte, entry *sessionEntry, plaintext []byte, pump *controlPump) error {
	if entry == nil || len(envelope) != wire.EnvelopeSize {
		return link.ErrEndToEndMessage
	}
	if entry.isTerminated() {
		// A scoped resource refusal already failed this Session. Its inbound
		// frames are consumed without touching any Circuit state; the physical
		// Link keeps serving every other Session.
		traceDataPlane("inbound frame for a terminated Session dropped", "kind", uint8(messageType))
		return nil
	}
	from := circuit.NodeID(envelopeNode(envelope, envelopeSrcOffset))
	sessionRef := circuit.SessionRef{
		ID:             circuit.SessionID(entry.id),
		PathID:         entry.scope.id,
		PathGeneration: entry.scope.gen,
	}
	switch messageType {
	case wire.MessageTypeControlRPC:
		// Classify before charging. Every session-lifecycle opcode spends one
		// shared control token, but WINDOW_UPDATE is receive-side credit feedback:
		// it is generated by this node's own drain rate and cannot be amplified by
		// the peer, so it is exempt on both halves. Charging it made the per-Link
		// control budget (sized for open/ready/reset) cap bulk throughput at one
		// window per token. The opcode is read from the decrypted plaintext, which
		// is already authenticated by the hop AEAD, so the exemption cannot be
		// spoofed by a frame that merely claims to be flow control.
		code, err := circuit.DecodeControlRPCCode(plaintext)
		if err != nil {
			return err
		}
		if code != circuit.RPCWindowUpdate {
			if !rt.chargeIngressControlRPC(pump, entry) {
				// Handled scoped refusal: the offending Session is already failed
				// and the frame is consumed without further decode. This is
				// deliberately not an error, because the pump read loop treats any
				// error as a physical Link failure.
				return nil
			}
		}
		switch code {
		case circuit.RPCOpen:
			open, err := circuit.DecodeOpenMessage(plaintext)
			if err != nil {
				return err
			}
			open.FromNodeID = from
			open.Session = sessionRef
			if err := rt.checkOpenCandidate(entry, open); err != nil {
				return err
			}
			return rt.handleInboundOpen(entry, open)
		case circuit.RPCReady:
			ready, err := circuit.DecodeReadyMessage(plaintext)
			if err != nil {
				return err
			}
			// FromNodeID is the authenticated responder; the manager checks it
			// against the source record's target before applying the READY, so a
			// third party cannot satisfy the open/cancel correlation.
			ready.FromNodeID = from
			traceDataPlane("CIRCUIT_READY received", "circuit", hexNode([16]byte(ready.CircuitID))[:8], "status", ready.Status.String())
			return rt.circuits.HandleReady(ready)
		case circuit.RPCStreamReset:
			reset, err := circuit.DecodeResetMessage(plaintext)
			if err != nil {
				return err
			}
			reset.FromNodeID = from
			traceDataPlane("STREAM_RESET received", "local", hexNode(rt.localID)[:8], "circuit", hexNode([16]byte(reset.CircuitID))[:8], "reason", uint32(reset.Reason), "from", hexNode([16]byte(from))[:8])
			return rt.circuits.HandleReset(reset)
		case circuit.RPCWindowUpdate:
			update, err := circuit.DecodeWindowUpdate(plaintext)
			if err != nil {
				return err
			}
			update.FromNodeID = from
			return rt.circuits.HandleWindowUpdate(update)
		default:
			return circuit.ErrUnsupportedControl
		}
	case wire.MessageTypeStreamData:
		data, err := circuit.DecodeStreamData(plaintext)
		if err != nil {
			return err
		}
		data.FromNodeID = from
		_, err = rt.circuits.HandleStreamData(data)
		return err
	default:
		return circuit.ErrUnsupportedControl
	}
}

// checkOpenCandidate verifies that an inbound CIRCUIT_OPEN names exactly the
// installed Path this session rides on. The Open carries candidate PathID,
// generation and digest; the target must not create a stream for a candidate it
// never accepted, so the check runs before HandleOpen changes any state.
func (rt *streamRuntime) checkOpenCandidate(entry *sessionEntry, open circuit.OpenMessage) error {
	ps := rt.pathByScope(entry.scope)
	if ps == nil {
		return fmt.Errorf("%w: session path is not installed", link.ErrRouteMessage)
	}
	if open.PathID != ps.scope.id || open.PathGeneration != ps.scope.gen {
		return fmt.Errorf("%w: CIRCUIT_OPEN path %d/%d, installed %d/%d", link.ErrRouteMessage, open.PathID, open.PathGeneration, ps.scope.id, ps.scope.gen)
	}
	if open.PathDigest != ps.digest {
		return fmt.Errorf("%w: CIRCUIT_OPEN digest does not match installed path", link.ErrRouteMessage)
	}
	return nil
}

// handleInboundOpen authorizes an inbound CIRCUIT_OPEN. A port with no virtual
// listener is refused with the same request identity as TARGET_REFUSED before
// the target manager ever creates a stream; otherwise the manager creates the
// stream and the accept loop hands it to the matching listener. entry is the
// arrival session resolved from the authenticated E2E frame, not from the
// envelope's zero SessionRef.
func (rt *streamRuntime) handleInboundOpen(entry *sessionEntry, open circuit.OpenMessage) error {
	if rt.listenerForPort(open.TargetPort) == nil {
		traceDataPlane("CIRCUIT_OPEN refused", "port", open.TargetPort)
		return rt.sendTargetRefused(entry, open)
	}
	traceDataPlane("CIRCUIT_OPEN accepted", "port", open.TargetPort)
	_, err := rt.circuits.HandleOpen(open)
	return err
}

// sendTargetRefused answers an Open for an unauthorized virtual port with a
// refusal that echoes the exact CircuitID/attempt/request_id. It is sealed with
// the session E2E protector, not sent as plaintext.
func (rt *streamRuntime) sendTargetRefused(entry *sessionEntry, open circuit.OpenMessage) error {
	refusal := circuit.ReadyMessage{
		CircuitID: open.CircuitID,
		Attempt:   open.Attempt,
		Status:    circuit.StatusRefused,
		ErrorCode: circuit.ReadyErrorTargetRefused,
		RequestID: open.RequestID,
	}
	payload, err := refusal.Encode()
	if err != nil {
		return err
	}
	sub := circuit.Submission{
		Dest:      circuit.NodeID(entry.src),
		Session:   circuit.SessionRef{ID: circuit.SessionID(entry.id), PathID: entry.scope.id, PathGeneration: entry.scope.gen},
		Direction: circuit.DirectionTargetToSource,
		Kind:      circuit.KindControlRPC,
		Body:      payload,
		PlainLen:  len(payload),
	}
	return rt.sendCircuitFrame(sub)
}

// forwardEndToEnd relays one opaque E2E frame along an installed path. The relay
// holds no session root: it checks its installed forwarding entry and the
// admitted-session hop domain only, and never calls CommitEndToEnd (which is the
// endpoint's authenticated inner-tag evidence, not a hop fact).
func (rt *streamRuntime) forwardEndToEnd(pump *controlPump, message link.ProtectedMessage, pathID uint64, pathGen uint32) error {
	ps := rt.pathByScope(pathScope{id: pathID, gen: pathGen})
	if ps == nil || !ps.relay {
		return link.ErrEndToEndMessage
	}
	hop := message.Hop()
	if int(hop.Cursor) != ps.localIndex {
		return link.ErrInvalidHopRoute
	}
	forward, reverse := ps.directionOnPath(message.Envelope)
	if !forward && !reverse {
		return link.ErrEndToEndMessage
	}
	if err := rt.checkIngressPeer(ps, pump, forward, true); err != nil {
		return err
	}
	sessionID := envelopeSessionID(message.Envelope)
	entry := rt.sessionEntryByID(session.SessionID(sessionID))
	if entry == nil || !entry.relay {
		// A relay only forwards a session it observed in the SESSION_CTRL
		// bootstrap; an unknown SessionID is never implicitly admitted.
		return link.ErrSessionNotAdmitted
	}
	if err := rt.admitSessionOnDataPumps(entry); err != nil {
		return err
	}
	if entry.relayPathBroken() {
		// Scoped terminal: a previous resource refusal already broke this relay
		// Session's forwarding path. Nothing more is charged, staged or
		// forwarded for it; the physical Link and every other Session stay
		// healthy. Every later frame of the broken path is traced so it is a
		// counted, visible drop rather than a silent consumption.
		traceDataPlane("relay frame dropped on a broken forwarding path",
			"session", hexNode([16]byte(entry.id))[:8], "kind", uint8(envelopeMessageType(message.Envelope)))
		return nil
	}
	// A rootless relay cannot decode the inner payload, but the authenticated
	// envelope names CONTROL_RPC exactly, so the ingress half of the frozen
	// per-Link/Network control budget is charged once here, on the exact ingress
	// Link, before this frame is staged or forwarded. Data frames are not
	// control and are never charged on the relay path. A refusal is scoped: it
	// latches this relay path broken and consumes the frame, never the Link.
	if envelopeMessageType(message.Envelope) == wire.MessageTypeControlRPC {
		if err := rt.chargeRelayControlRPC(pump, true); err != nil {
			entry.markRelayPathBroken()
			return nil
		}
	}
	if !entry.isReady() {
		// Data must not overtake the relay's SESSION_READY commit: stage the
		// still-hop-protected ciphertext and drain it in order once ready. The
		// ingress pump is the exact physical Link instance that owns the copy. A
		// shared-allocator refusal is a scoped failure of this relay Session's
		// forwarding path; the physical Link stays healthy.
		if err := rt.stageRelayFrame(entry, pump, message.Envelope, message.Payload, hop); err != nil {
			if errors.Is(err, errRelayStagedRefused) {
				return nil
			}
			return err
		}
		return nil
	}
	if err := rt.forwardOpaque(ps, message.Envelope, message.Payload, hop); err != nil {
		if errors.Is(err, errRelayStagedRefused) {
			entry.markRelayPathBroken()
			return nil
		}
		return err
	}
	return nil
}

// forwardElapsedMicros is the local processing/queueing cost of one relayed
// frame, measured from this call's start rather than from the previous frame.
// The hop budget meters one transaction's traversal: charging the idle gap of a
// long-lived Ready path would exhaust the budget of any business stream after
// its first idle period, even though nothing about the current frame is late.
// The >=1 floor keeps the budget strictly non-increasing per hop, so it is never
// refilled by a fast forward.
func forwardElapsedMicros(start time.Time) uint32 {
	elapsed := time.Since(start).Microseconds()
	if elapsed <= 0 {
		return 1
	}
	if elapsed > int64(^uint32(0)) {
		return ^uint32(0)
	}
	return uint32(elapsed)
}

// --- virtual Stream ----------------------------------------------------------

// circuitStream is the net.Conn view of one Circuit. Deadlines are realized by
// per-call contexts so a later SetDeadline cancels an in-flight read/write in
// real time through the circuit's own wait path.
type circuitStream struct {
	rt     *streamRuntime
	c      *circuit.Circuit
	remote NodeID
	key    circuit.Key

	mu        sync.Mutex
	readDL    time.Time
	writeDL   time.Time
	readGen   uint64
	writeGen  uint64
	readWake  chan struct{}
	writeWake chan struct{}
	closed    atomic.Bool
	closeOne  sync.Once
}

func newCircuitStream(rt *streamRuntime, c *circuit.Circuit, remote NodeID) *circuitStream {
	return &circuitStream{
		rt:        rt,
		c:         c,
		remote:    remote,
		key:       c.Key(),
		readWake:  make(chan struct{}),
		writeWake: make(chan struct{}),
	}
}

// refillWindow advertises the next absolute receive credit after the
// application consumed bytes: keep exactly one frozen InitialWindow of unread
// credit ahead of the current receive base. The manager rejects a regressed or
// over-buffer value, so a racing second reader is harmless.
func (s *circuitStream) refillWindow() {
	c, err := s.circuits().Lookup(s.key)
	if err != nil {
		return
	}
	buffered := uint64(c.Buffered())
	next := c.RecvNext()
	if next < buffered {
		return
	}
	base := next - buffered
	if base > ^uint64(0)-circuit.InitialWindow {
		return
	}
	// Keep a full MaxBuffer of credit ahead, and only top it up once the peer has
	// consumed more than half of it. Each WINDOW_UPDATE is a CONTROL_RPC that
	// spends a shared per-Link control token, so the number of updates a bulk
	// transfer needs is a throughput limit, not a detail: with a 64 KiB frontier
	// a large transfer paid one update per frame and the control budget throttled
	// it to a few MB/s. Both the initial credit (InitialWindow) and its
	// per-update growth are bounded by MaxCreditAhead on the sender side, so
	// advertising MaxBuffer stays inside what the peer accepts.
	// Top up late: wait until only an eighth of the frontier is still advertised.
	// A sender needs one round trip of credit in hand to keep the pipe full, and
	// an eighth of 256 KiB is 32 KiB, which is still more than one maximum frame,
	// so the peer never stalls. Topping up earlier just pays more control tokens
	// for the same transfer.
	if already := c.RecvWindow(); already > base {
		// Top up earlier than an eighth of the frontier: the sender stalls once the
		// advertised credit runs out, and with an 8 MiB frontier a quarter leaves
		// 2 MiB of slack, which is more than one round trip of data at any link
		// this transport targets. An eighth left only 1 MiB of slack and the sender
		// could reach the end of its credit before the next update landed.
		if advertised := already - base; advertised >= uint64(circuit.MaxBuffer)/4 {
			return
		}
	}
	abs := base + uint64(circuit.MaxBuffer)
	if abs <= c.RecvWindow() {
		return
	}
	if err := c.WindowUpdate(abs); err != nil {
		traceDataPlane("WINDOW_UPDATE not sent", "window", abs, "err", err.Error())
	}
}

func (s *circuitStream) Read(p []byte) (int, error) {
	for {
		ctx, cancel, generation := s.operation(&s.readDL, &s.readGen, &s.readWake)
		n, err := s.circuits().ReadData(ctx, s.key, p)
		cancel()
		if n > 0 {
			// The circuit manager advances its receive frontier but never
			// advertises it; without this WINDOW_UPDATE the peer's send credit
			// is stuck at the initial 64 KiB and any Write above one window
			// deadlocks.
			s.refillWindow()
		}
		if n > 0 || err == nil {
			return n, mapStreamError(err)
		}
		// A deadline change cancels the in-flight wait so the caller restarts
		// with the new deadline; any other terminal cause is returned as-is.
		if isDeadlineCancellation(err) && s.generationChanged(generation, &s.readGen) {
			continue
		}
		return 0, mapStreamError(err)
	}
}

func (s *circuitStream) Write(p []byte) (int, error) {
	for {
		ctx, cancel, generation := s.operation(&s.writeDL, &s.writeGen, &s.writeWake)
		n, err := s.circuits().WriteData(ctx, s.key, p)
		cancel()
		if n > 0 || err == nil {
			return n, mapStreamError(err)
		}
		if isDeadlineCancellation(err) && s.generationChanged(generation, &s.writeGen) {
			continue
		}
		return 0, mapStreamError(err)
	}
}

// operation builds the per-call context of one Read/Write plus a watcher that a
// concurrent SetDeadline closes to cancel exactly this in-flight wait. The
// returned generation identifies the deadline value in force, so the caller can
// tell a deadline change from a real expiry.
func (s *circuitStream) operation(deadline *time.Time, generation *uint64, wake *chan struct{}) (context.Context, context.CancelFunc, uint64) {
	s.mu.Lock()
	currentGen := *generation
	value := *deadline
	w := *wake
	s.mu.Unlock()
	ctx, cancel := s.ctx(value)
	go func() {
		select {
		case <-w:
			cancel()
		case <-ctx.Done():
		}
	}()
	return ctx, cancel, currentGen
}

// generationChanged reports whether a SetDeadline bumped the generation since the
// operation captured it.
func (s *circuitStream) generationChanged(generation uint64, current *uint64) bool {
	s.mu.Lock()
	defer s.mu.Unlock()
	return *current != generation
}

// isDeadlineCancellation reports whether err is the cancellation of an in-flight
// wait rather than a terminal stream cause.
func isDeadlineCancellation(err error) bool {
	return errors.Is(err, context.Canceled) || errors.Is(err, context.DeadlineExceeded)
}

func (s *circuitStream) CloseWrite() error {
	return mapStreamError(s.circuits().CloseWrite(s.key))
}

func (s *circuitStream) Reset(code uint32) error {
	return mapStreamError(s.circuits().Reset(s.key, circuit.ResetReason(code)))
}

func (s *circuitStream) Close() error {
	var err error
	s.closeOne.Do(func() {
		s.closed.Store(true)
		err = mapStreamError(s.circuits().CloseCircuit(s.key))
	})
	return err
}

func (s *circuitStream) RemoteNode() NodeID { return s.remote }

func (s *circuitStream) LocalAddr() net.Addr  { return streamAddr("overlay") }
func (s *circuitStream) RemoteAddr() net.Addr { return streamAddr(s.remote) }

func (s *circuitStream) SetDeadline(t time.Time) error {
	s.mu.Lock()
	s.readDL, s.writeDL = t, t
	s.bumpReadLocked()
	s.bumpWriteLocked()
	s.mu.Unlock()
	return nil
}

func (s *circuitStream) SetReadDeadline(t time.Time) error {
	s.mu.Lock()
	s.readDL = t
	s.bumpReadLocked()
	s.mu.Unlock()
	return nil
}

func (s *circuitStream) SetWriteDeadline(t time.Time) error {
	s.mu.Lock()
	s.writeDL = t
	s.bumpWriteLocked()
	s.mu.Unlock()
	return nil
}

// bumpReadLocked cancels any in-flight Read so it restarts with the new
// deadline. Called with s.mu held.
func (s *circuitStream) bumpReadLocked() {
	s.readGen++
	close(s.readWake)
	s.readWake = make(chan struct{})
}

// bumpWriteLocked cancels any in-flight Write so it restarts with the new
// deadline. Called with s.mu held.
func (s *circuitStream) bumpWriteLocked() {
	s.writeGen++
	close(s.writeWake)
	s.writeWake = make(chan struct{})
}

func (s *circuitStream) readDeadline() time.Time {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.readDL
}

func (s *circuitStream) writeDeadline() time.Time {
	s.mu.Lock()
	defer s.mu.Unlock()
	return s.writeDL
}

func (s *circuitStream) ctx(deadline time.Time) (context.Context, context.CancelFunc) {
	if deadline.IsZero() {
		return context.WithCancel(s.rt.n.ctx)
	}
	return context.WithDeadline(s.rt.n.ctx, deadline)
}

func (s *circuitStream) circuits() *circuit.Manager { return s.rt.circuits }

// mapStreamError translates circuit-layer terminal sentinels onto the SDK error
// surface. A deadline/shutdown is reported as such instead of being retried into
// a new Circuit.
func mapStreamError(err error) error {
	switch {
	case err == nil:
		return nil
	case errors.Is(err, circuit.ErrCanceled), errors.Is(err, circuit.ErrClosed):
		return ErrClosed
	case errors.Is(err, circuit.ErrSessionLost), errors.Is(err, circuit.ErrLinkDown):
		return ErrSessionLost
	case errors.Is(err, circuit.ErrNoRoute):
		return ErrNoRoute
	case errors.Is(err, circuit.ErrResource):
		return ErrResource
	case errors.Is(err, circuit.ErrWriteClosed):
		return net.ErrClosed
	case errors.Is(err, context.DeadlineExceeded), errors.Is(err, os.ErrDeadlineExceeded):
		return ErrDeadline
	case errors.Is(err, circuit.ErrStreamReset):
		return fmt.Errorf("%w: %v", ErrStreamReset, err)
	default:
		return err
	}
}

